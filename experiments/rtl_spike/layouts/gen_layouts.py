"""Generate the two spike layouts (owner decisions 2026-10-23) from src/config.json. Same RTL, different macro placement.

    python3 gen_layouts.py          # writes a/config.json and b/config.json next to this file

A, opposite edges: u_m0 FS on the bottom die edge (pins up), u_m1 N near the top (pins down), same x; u_loc FS beside
   u_m0 (pins up); a 40 um placement-blocked corridor above u_m1 (the TT I/O pins are on the top edge, x 29.8-191.0,
   template tt_block_8x4_pgvdd.def).
B, one wall: u_m0 and u_m1 FS side by side on the bottom edge (pins up); logic above. The two 64x64 (2 x 784.48 um)
   and the 64x16 (236.8 um) do not fit in one row of the 1718.4 um core, so u_loc goes to the top-left, N (pins down),
   at the same x as u_m0: its power columns then lie on u_m0's left-half columns, which the stripe step requires of
   macros that share an x range; a 40 um corridor above it stays free for the I/O pins.
Both: no band obstructions; macro ROUTING_OBSTRUCTIONS, CTS_OBSTRUCTION_AWARE and 200 um repair wire length kept;
   GRT_ALLOW_CONGESTION off (global routing fails fast instead of planning through macros); 15-pass detailed-route
   cap; LVS, Magic stream-out / LEF and the IR-drop report skipped (timing runs, not sign-off).
"""
import collections
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "macro_floorplan"))
import gen_variants as g  # noqa: E402

M64, M16 = "RM_IHPSG13_1P_64x64_c2_bm_bist", "RM_IHPSG13_1P_64x16_c2"
CORE = (2.88, 3.78, 1721.28, 706.86)
TOP_Y = 601.02                       # 3.78 * 159: top of a 64.36 um macro at 665.38, 41.5 um below the core top

LAYOUTS = {
    "a": {"tiles": [("u_m0", 0, 0, 464.2, 3.78, "FS"), ("u_m1", 0, 0, 464.2, TOP_Y, "N"),
                    ("u_loc", 2, 0, 216.92, 3.78, "FS")],
          "corridor": [[464.2, TOP_Y + 64.36, 1248.68, CORE[3]]]},
    "b": {"tiles": [("u_m0", 0, 0, 3.36, 3.78, "FS"), ("u_m1", 0, 0, 801.4, 3.78, "FS"),
                    ("u_loc", 2, 0, 3.36, TOP_Y, "N")],
          "corridor": [[CORE[0], TOP_Y + 64.36, 240.16, CORE[3]]]},
}


def check(name, tiles):
    """Inside the core, no overlaps; macros sharing an x range must start at the same x (column alignment)."""
    boxes = [(i, k, x, y, x + g.SIZE[k][0], y + g.SIZE[k][1]) for i, k, _, x, y, _ in tiles]
    for a in boxes:
        assert CORE[0] <= a[2] and a[4] <= CORE[2] and CORE[1] <= a[3] and a[5] <= CORE[3], (name, a)
        for b in boxes:
            if a[0] >= b[0]:
                continue
            xo = a[2] < b[4] + 2.0 and b[2] < a[4] + 2.0
            assert not (xo and a[3] < b[5] + 0.48 and b[3] < a[5] + 0.48), (name, a, b)
            if xo and a[1] != b[1]:
                assert a[2] == b[2], f"{name}: {a[0]} and {b[0]} share an x range off the same column grid"


def main():
    base = json.load(open(os.path.join(HERE, "..", "src", "config.json")), object_pairs_hook=collections.OrderedDict)
    for name, lay in LAYOUTS.items():
        check(name, lay["tiles"])
        d = collections.OrderedDict((k, v) for k, v in base.items() if not k.startswith("//3spike"))
        d["//layout"] = f"generated by experiments/rtl_spike/layouts/gen_layouts.py, layout {name.upper()}; do not edit"
        inst = {i: {"location": [x, y], "orientation": o} for i, _k, _t, x, y, o in lay["tiles"]}
        d["MACROS"][M64]["instances"] = collections.OrderedDict((i, inst[i]) for i in ("u_m0", "u_m1"))
        d["MACROS"][M16]["instances"] = {"u_loc": inst["u_loc"]}
        d["ROUTING_OBSTRUCTIONS"] = g.obstructions(lay["tiles"])
        d["FP_OBSTRUCTIONS"] = lay["corridor"]
        d["CTS_OBSTRUCTION_AWARE"] = True
        d["DESIGN_REPAIR_MAX_WIRE_LENGTH"] = 200
        d["GRT_DESIGN_REPAIR_MAX_WIRE_LENGTH"] = 200
        d["GRT_ALLOW_CONGESTION"] = False
        d["DRT_OPT_ITERS"] = 15
        for k in ("RUN_LVS", "RUN_MAGIC_STREAMOUT", "RUN_MAGIC_WRITE_LEF", "RUN_IRDROP_REPORT"):
            d[k] = False
        os.makedirs(os.path.join(HERE, name), exist_ok=True)
        with open(os.path.join(HERE, name, "config.json"), "w") as f:
            json.dump(d, f, indent=2)
            f.write("\n")
        print(name, {i: (v["location"], v["orientation"]) for i, v in inst.items()}, "corridor", lay["corridor"])


if __name__ == "__main__":
    main()
