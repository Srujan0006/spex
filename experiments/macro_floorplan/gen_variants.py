"""Generate the floorplan experiment variants (Gate A condition 2) from one description.

    python3 gen_variants.py          # writes variants/<name>/{info.yaml, src/...}

Every file it writes says it is generated; edit this script, not the outputs. Filler sizing (2026-10-20): per engine
the measured v4b area-probe estimate, 268,888 um^2 (experiments/area_probe, s4b.ys, yowasp-yosys 0.70, typical
corner), plus 0.05 mm^2 of host/trace/glue [Estimate, proposal section 4]; the table filler of common/fp_tile.v costs
about 955 um^2 per 8-bit word plus a 3.5-7.4k um^2 base per tile [Measured: yosys 0.33, local, see
docs/notes/GATE_A.md], so an engine is m0 TW=128 + m1 TW=128 + loc TW=16 (~278k um^2) and the glue is TW=64 on the
coverage tile (~66k um^2). Placement: 64x64 pairs stacked at x = 3.36 (FS/N, pins facing a logic channel), 64x16
location-word macros stacked at x = 812.64, coverage at the bottom right; macros of different widths never share an
x range (see README.md, stripe findings). x = 3.36 + 11.24 i and y = 3.78 k keep every macro on PRISM's stripe grid.
"""
import json
import os
import re
import shutil
import subprocess

HERE = os.path.dirname(os.path.abspath(__file__))
# PL_TARGET_DENSITY_PCT per variant: it must exceed the design's utilisation (GPL-0302); two_engine's first run
# (CI 39430571597) had effective utilisation 0.792 at the template's 60 % and failed detailed placement.
DENSITY = {"two_engine": 85, "asym": 72, "one_engine": 60}
COMMON = os.path.join(HERE, "common")
GEN = "generated by experiments/macro_floorplan/gen_variants.py; do not edit"
P = "pdk_dir::libs.ref/sg13cmos5l_sram"
M = {0: "RM_IHPSG13_1P_64x64_c2_bm_bist", 1: "RM_IHPSG13_1P_256x32_c2_bm_bist", 2: "RM_IHPSG13_1P_64x16_c2"}
SUB = {0: "g_m64", 1: "g_m32", 2: "g_m16"}

# name: [(instance, kind, TW, x, y, orientation)]
VARIANTS = {
    "two_engine": [
        ("u_e0_m0", 0, 128, 3.36, 3.78, "FS"), ("u_e0_m1", 0, 128, 3.36, 189.0, "N"),
        ("u_e1_m0", 0, 128, 3.36, 389.34, "FS"), ("u_e1_m1", 0, 128, 3.36, 574.56, "N"),
        ("u_e0_loc", 2, 16, 812.64, 3.78, "FS"), ("u_e1_loc", 2, 16, 812.64, 189.0, "N"),
        ("u_cov", 1, 64, 1295.96, 3.78, "FS"),
    ],
    # S46: one full engine plus one Check-only engine (ta_engine_lite.v, 103,667 um^2 [Measured, slite.ys]):
    # the Check-only engine's tiles are sized to ~114k um^2 (TW 64 + 32 + 4)
    "asym": [
        ("u_e0_m0", 0, 128, 3.36, 3.78, "FS"), ("u_e0_m1", 0, 128, 3.36, 189.0, "N"),
        ("u_e1_m0", 0, 64, 3.36, 389.34, "FS"), ("u_e1_m1", 0, 32, 3.36, 574.56, "N"),
        ("u_e0_loc", 2, 16, 812.64, 3.78, "FS"), ("u_e1_loc", 2, 4, 812.64, 189.0, "N"),
        ("u_cov", 1, 64, 1295.96, 3.78, "FS"),
    ],
    "one_engine": [
        ("u_e0_m0", 0, 128, 3.36, 3.78, "FS"), ("u_e0_m1", 0, 128, 3.36, 189.0, "N"),
        ("u_e0_loc", 2, 16, 812.64, 3.78, "FS"),
        ("u_cov", 1, 64, 1295.96, 3.78, "FS"),
    ],
}


def project_v(name, tiles):
    top = f"tt_um_srujan0006_fp_{name}"
    lines = [f"// {GEN}", f"// SPEX floorplan experiment {name} (not a design). SPDX-License-Identifier: Apache-2.0",
             "`default_nettype none", f"module {top} (",
             "    input  wire [7:0] ui_in, output wire [7:0] uo_out, input  wire [7:0] uio_in,",
             "    output wire [7:0] uio_out, output wire [7:0] uio_oe, input  wire ena, input  wire clk,",
             "    input  wire rst_n", ");", f"    wire [{len(tiles) - 1}:0] d;"]
    for i, (inst, kind, tw, *_ ) in enumerate(tiles):
        din = ["ui_in", "uio_in", "~ui_in", "ui_in ^ uio_in", "ui_in + uio_in", "uio_in - ui_in", "{ui_in[3:0], uio_in[7:4]}"][i % 7]
        lines.append(f"    fp_tile #(.KIND({kind}), .TW({tw}), .SEED(32'h{(i * 0x1F3 + 1):08x})) {inst} "
                     f"(.clk(clk), .rst_n(rst_n), .din({din}), .dout(d[{i}]));")
    lines += [f"    assign uo_out = {{{8 - len(tiles)}'b0, d}};" if len(tiles) < 8 else "    assign uo_out = d[7:0];",
              "    assign uio_out = 8'h00;", "    assign uio_oe = 8'h00;", "    wire _unused = &{ena, 1'b0};",
              "endmodule", ""]
    return top, "\n".join(lines)


def _conn(tile):
    inst, kind = tile[0], tile[1]
    esc = f"{inst}.{SUB[kind]}.u_sram".replace(".", "\\.")
    return [f"{esc} VPWR VGND VDD! VSS!"] + ([f"{esc} VPWR VGND VDDARRAY! VSS!"] if kind != 2 else [])


def config(tiles):
    macros = {}
    conn = []
    for inst, kind, tw, x, y, orient in tiles:
        name = M[kind]
        m = macros.setdefault(name, {
            "instances": {},
            "gds": [f"{P}/gds/{name}.gds"], "lef": [f"{P}/lef/{name}.lef"],
            "lib": {"nom_typ_1p20V_25C": [f"{P}/lib/{name}_typ_1p20V_25C.lib"],
                    "nom_fast_1p32V_m40C": [f"{P}/lib/{name}_fast_1p32V_m55C.lib"],
                    "nom_slow_1p08V_125C": [f"{P}/lib/{name}_slow_1p08V_125C.lib"]},
            "nl": [f"dir::{name}.v"], "spice": [f"{P}/cdl/{name}.cdl"]})
        path = f"{inst}.{SUB[kind]}.u_sram"
        m["instances"][path] = {"location": [x, y], "orientation": orient}
        esc = path.replace(".", "\\.")
        conn += [f"{esc} VPWR VGND VDD! VSS!"] + ([f"{esc} VPWR VGND VDDARRAY! VSS!"] if kind != 2 else [])
    template = json.load(open(os.path.join(HERE, "fp5", "src", "config.json")))
    cfg = {"//": f"{GEN}. Recipe credits as in fp5/src/config.json (Loom, PRISM)."}
    for k, v in template.items():
        if k in ("//", "MACROS", "PDN_MACRO_CONNECTIONS", "VERILOG_DEFINES"):
            continue
        cfg[k] = v
    cfg["MACROS"] = macros
    return cfg
    cfg["PDN_MACRO_CONNECTIONS"] = conn


def check_instances(src, top, tiles):
    """The MACROS instance paths must be the flattened names Yosys gives the macro cells (LibreLane's
    CheckMacroInstances fails otherwise; an else-if generate chain adds an implicit genblk level)."""
    if not shutil.which("yosys"):
        print("  yosys not found: instance paths not checked")
        return
    libs = " ".join(sorted(f for f in os.listdir(src) if f.startswith("RM_") and f.endswith(".v")))
    r = subprocess.run(["yosys", "-p", f"read_verilog -sv project.v fp_tile.v; read_verilog -lib {libs}; "
                        f"synth -flatten -top {top}; select -list t:RM_*"], cwd=src, capture_output=True, text=True)
    got = set(re.findall(rf"{top}/(\S+)", r.stdout))
    want = {f"{inst}.{SUB[kind]}.u_sram" for inst, kind, *_ in tiles}
    if got != want:
        raise SystemExit(f"macro instance paths differ: yosys {sorted(got)} vs config {sorted(want)}")


def main():
    for name, tiles in VARIANTS.items():
        d = os.path.join(HERE, "variants", name)
        src = os.path.join(d, "src")
        shutil.rmtree(d, ignore_errors=True)
        os.makedirs(src)
        top, v = project_v(name, tiles)
        open(os.path.join(src, "project.v"), "w").write(v)
        for f in ("fp_tile.v", "pdn_cfg.tcl") + tuple(f"{M[k]}.v" for k in sorted({t[1] for t in tiles})):
            shutil.copy(os.path.join(COMMON, f), src)
        cfg = config(tiles)
        cfg["PDN_MACRO_CONNECTIONS"] = [c for t in tiles for c in _conn(t)]
        cfg["PL_TARGET_DENSITY_PCT"] = DENSITY[name]
        json.dump(cfg, open(os.path.join(src, "config.json"), "w"), indent=2)
        info = open(os.path.join(HERE, "fp5", "info.yaml")).read()
        info = info.replace('title:        "SPEX floorplan experiment fp5"', f'title:        "SPEX floorplan experiment {name}"')
        info = info.replace('top_module:  "tt_um_srujan0006_fp5"', f'top_module:  "{top}"')
        open(os.path.join(d, "info.yaml"), "w").write(f"# {GEN}\n" + info)
        check_instances(src, top, tiles)
        print(f"{name}: {len(tiles)} macros -> {d}")


if __name__ == "__main__":
    main()
