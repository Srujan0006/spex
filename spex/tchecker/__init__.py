"""Export a SPEX spec to TChecker's input language (step 6; SEMANTICS R3.3: the nondeterministic spec covers every
policy and priority order).

The spec becomes one process. Its timing is kept exactly:
  - POLICY and WIN windows become guards lo <= x <= hi; GE becomes x >= lo;
  - location invariants are kept, and a location left only by clock-triggered internal edges gets the invariant
    x <= min(lo) of those edges (they are urgent in hardware, R3.1, and fire at exactly lo, R4.5);
  - clock resets become x = 0.
Data is abstracted, which over-approximates the hardware (a safety property proven here still holds):
  - the bit counter is a bounded int (SHIN / SHOUT add 1, LOAD / PUSH / CLR and their combinations clear it), so
    BITCNT_EQ / BITCNT_LT guards are exact;
  - shift-register values, TX FIFO state and host tokens are free: SR_MATCH, TXF_NE and TOKEN guards are dropped;
  - pin values are not modelled; spec edges named in `events` become synchronising events for observers.
Events between engines (SEMANTICS §10) are not exported (R10.3, deferred).

    text = export(spec, events={"start bit": "start", "stop bit": "stop"}, observers=[NO_DOUBLE_START])
"""
from __future__ import annotations

import re
from dataclasses import dataclass
from typing import Dict, List, Optional, Sequence

from spex.dsl import Spec

BITCNT_MAX = 63
COUNT_OPS = {"SHIN", "SHOUT"}
CLEAR_OPS = {"LOAD", "PUSH", "LOAD_PUSH", "LOAD_PEEK", "CLR", "PUSH_LOAD_PEEK"}


@dataclass
class Observer:
    """A small timed automaton over spec events. edges: (src, dst, event) or (src, dst, event, guard, do) with
    TChecker guard / statement text over the observer's own `clocks`; `bad` locations are labelled `bad`.
    A location with no edge at all for an event gets a self-loop on it, so an untimed observer never blocks the spec;
    a timed observer must cover every case of its guards itself (it may block on purpose only in a `bad` location)."""
    name: str
    locations: Sequence[str]
    initial: str
    edges: Sequence[tuple]
    bad: Sequence[str] = ("bad",)
    clocks: Sequence[str] = ()


def frame_time(lo: int, hi: int) -> Observer:
    """Every stop event comes lo..hi cycles after the start event of its frame."""
    obs = Observer(
        name="obs_time",
        locations=["idle", "frame", "ok", "bad"],
        initial="idle",
        clocks=["y"],
        edges=[("idle", "frame", "start", "", "y=0"),
               ("ok", "frame", "start", "", "y=0"),
               ("frame", "ok", "stop", f"y>={lo}&&y<={hi}", ""),
               ("frame", "bad", "stop", f"y<{lo}", ""),
               ("frame", "bad", "stop", f"y>{hi}", ""),
               ("frame", "bad", "start", "", "")],
    )
    obs.ok = ("ok",)                                  # label a well-timed frame end: reachable, or the check is vacuous
    return obs


NO_DOUBLE_START = Observer(
    name="obs_frame",
    locations=["idle", "frame", "bad"],
    initial="idle",
    edges=[("idle", "frame", "start"), ("frame", "idle", "stop"), ("frame", "bad", "start")],
)


def _ident(s: str) -> str:
    out = "".join(c if c.isalnum() else "_" for c in s)
    return out if out[0].isalpha() else "L" + out


def _guard(spec: Spec, e) -> List[str]:
    g = []
    if e.window is not None and e.ck is not None:
        x = _ident(e.window.clock)
        if e.ck in ("WIN", "POLICY"):
            g += [f"{x}>={e.window.lo}", f"{x}<={e.window.hi}"]
        elif e.ck == "GE":
            g.append(f"{x}>={e.window.lo}")
    if e.data is not None:
        if e.data.kind == "BITCNT_EQ":
            g.append(f"bitcnt=={e.data.value & 0xFF}")
        elif e.data.kind == "BITCNT_LT":
            g.append(f"bitcnt<{e.data.value & 0xFF}")
    return g


def _do(spec: Spec, e) -> List[str]:
    d = [f"{_ident(c)}=0" for c in e.reset]
    if e.op.kind in COUNT_OPS:
        d.append(f"bitcnt=bitcnt+1")
    elif e.op.kind in CLEAR_OPS:
        d.append("bitcnt=0")
    return d


def _attrs(**kv) -> str:
    items = [f"{k}:" if v is True else f"{k}: {v}" for k, v in kv.items() if v]
    return "{" + " : ".join(items) + "}" if items else ""


def export(spec: Spec, events: Optional[Dict[str, str]] = None, observers: Sequence[Observer] = (),
           name: Optional[str] = None) -> str:
    events = dict(events or {})
    labels = {e.label for e in spec.edges}
    missing = set(events) - labels
    if missing:
        raise ValueError(f"no spec edge labelled {sorted(missing)}")
    P = "spec"
    lines = [f"# generated by spex.tchecker from spec {spec.name}; do not edit", f"system:{_ident(name or spec.name)}"]
    obs_events = sorted(set(events.values()) | {e[2] for o in observers for e in o.edges})
    spec_events = []
    for i, e in enumerate(spec.edges):
        spec_events.append(events.get(e.label, f"e{i}"))
    for ev in sorted(set(spec_events) | set(obs_events)):
        lines.append(f"event:{ev}")
    for c in spec.clocks:
        lines.append(f"clock:1:{_ident(c)}")
    for o in observers:
        for c in o.clocks:
            lines.append(f"clock:1:{o.name}_{c}")
    lines.append(f"int:1:0:{BITCNT_MAX}:0:bitcnt")
    lines.append(f"process:{P}")
    for l in spec.locs:
        inv = []
        if l.invariant is not None:
            inv.append(f"{_ident(l.invariant.clock)}<={l.invariant.hi}")
        out = [e for e in spec.edges if e.src is l]
        if out and all(e.kind == "internal" and e.ck == "GE" for e in out):
            c = {e.window.clock for e in out}
            if len(c) == 1:
                inv.append(f"{_ident(c.pop())}<={min(e.window.lo for e in out)}")
        attrs = _attrs(initial=l is spec.initial_loc, invariant="&&".join(inv),
                       labels="halt" if l.halt else "")
        lines.append(f"location:{P}:{_ident(l.name)}{attrs}")
    for e, ev in zip(spec.edges, spec_events):
        lines.append(f"edge:{P}:{_ident(e.src.name)}:{_ident(e.dst.name)}:{ev}"
                     f"{_attrs(provided='&&'.join(_guard(spec, e)), do=';'.join(_do(spec, e)))}")
    for o in observers:
        lines.append(f"process:{o.name}")
        for loc in o.locations:
            lab = "bad" if loc in o.bad else ("ok" if loc in getattr(o, "ok", ()) else "")
            lines.append(f"location:{o.name}:{loc}{_attrs(initial=loc == o.initial, labels=lab)}")
        for edge in o.edges:
            src, dst, ev = edge[:3]
            guard, do = (edge[3], edge[4]) if len(edge) == 5 else ("", "")
            for c in o.clocks:                        # observer clocks are namespaced in the system
                guard = re.sub(rf"\b{c}\b", f"{o.name}_{c}", guard)
                do = re.sub(rf"\b{c}\b", f"{o.name}_{c}", do)
            lines.append(f"edge:{o.name}:{src}:{dst}:{ev}{_attrs(provided=guard, do=do)}")
        for loc in o.locations:
            for ev in obs_events:
                if not any(e[0] == loc and e[2] == ev for e in o.edges):
                    lines.append(f"edge:{o.name}:{loc}:{loc}:{ev}")
    for ev in obs_events:                          # one synchronisation per event: the spec and every observer
        if ev in set(spec_events) and observers:
            lines.append(f"sync:{P}@{ev}:" + ":".join(f"{o.name}@{ev}" for o in observers))
    return "\n".join(lines) + "\n"
